"use strict";
const assert=require("node:assert/strict");
const core=require("../sites/subtitle-sync-studio/public/subtitle-core.js");
const srt="1\n00:00:01,000 --> 00:00:03,000\nHello\n\n2\n00:00:02,500 --> 00:00:04,000\nSecond subtitle\n";
const vtt="WEBVTT\n\n00:01.000 --> 00:03.000\nHello\n\n00:03.000 --> 00:04.500\nWorld\n";
const a=core.parse(srt);assert.equal(a.cues.length,2);assert.equal(a.format,"srt");
assert.equal(a.cues[0].start,1000);assert.equal(a.cues[0].end,3000);
assert.equal(core.check(a.cues).filter(x=>x.type==="overlap").length,1);
const b=core.parse(vtt);assert.equal(b.cues.length,2);assert.equal(b.cues[0].start,1000);
assert.ok(core.exportText(b.cues,"srt").includes("00:00:01,000 --> 00:00:03,000"));
assert.ok(core.exportText(a.cues,"vtt").startsWith("WEBVTT"));
assert.equal(core.parse(core.exportText(a.cues,"vtt")).cues.length,2);
assert.equal(core.shift(a.cues,1500)[0].start,2500);
assert.equal(core.shift(a.cues,-4000)[0].start,0);
assert.equal(core.stretch([{start:25000,end:50000,text:"x"}],25,50)[0].end,25000);
assert.equal(core.substitute(a.cues,"Hello","Goodbye")[0].text,"Goodbye");
assert.deepEqual(core.check([{start:2,end:1,text:""},{start:1,end:2,text:"x"}]).map(x=>x.type),["duration","empty","order"]);
assert.equal(core.parse("WEBVTT\n\nNOTE hello\nskip\n\n00:00:01.000 --> 00:00:02.000\nOK\n").cues.length,1);
assert.throws(()=>core.parse("hello world"));
assert.throws(()=>core.stretch(a.cues,0,25));
console.log("subtitle core tests passed");